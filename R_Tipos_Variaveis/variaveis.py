"""
Variável: 

São usadas pra guardar valores. 
Por exemplo, nome_completo e idade armazenam strings e números, respectivamente.
"""

nome_completo = "Lucas Carvalho 1"
nomeCompleto = "Lucas Carvalho 2"

# -> Case sensitive <- nome_completo e nomeCompleto são nomes de variáveis distintos

print(nome_completo) #Snake case (ex.: nome_completo, minha_variavel) é o padrão do Python para variáveis, funções e métodos.
print(nomeCompleto) #Camel case (ex.: NomeCompleto, MinhaClasse) normalmente é utilizado para criar nomes de classes em Python, 

idade = 25

print("Variável idade:" ,idade)