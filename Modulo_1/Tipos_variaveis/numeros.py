#Número inteiro: Somente resultados redondos, inteiros

numero_inteiro = 1
print("Número inteiro: ", numero_inteiro)


#Real com ponto flutuante. Números com virgula, quebrados

numero_real = 3.14
print("Número real com ponto flutuante: ", numero_real)

#type() retorna o tipo da variável que está sendo utilizada
print("Tipo da variável -> numero_inteiro. ", type(numero_inteiro))
print("Tipo da variável -> numero_real. ", type(numero_real))


#Soma +
soma = 1+1
print ("A soma de 1+1 é: ", soma)

#Float SOMA
print ("A soma de 1+1 com ponto fluante é: ", float(soma))




#subtração 
subtracao = 1-1
print ("A soma de 1-1 é: ", subtracao)



#multiplicacao
multiplicacao = 2*2
print("A multiplicacao de 2*2 é :", multiplicacao)



#Divisão -> Sempre retorna ponto flutuante, deve utilizar o marcador INT
divisao = 6/2
print("A divisao com ponto flutuante de 6/2 é :", divisao)
print("Valor em inteiro da divisão: ", int(divisao))


#Divisão com resultado inteiro, usa //
divisao = 6//2
print("A divisao com ponto flutuante de 6/q2 é :", divisao)
print("Valor em inteiro da divisão: ", int(divisao))


#Modulo = Restante da divisão, utilizado para descobrir se o final do valor é par ou impar
modulo = 5%2
print("O modulo de 5%2 e: ", modulo)

